// Writes src/lib/pdf-font-coverage.ts: the Unicode code points that the PDF
// fonts can draw, so the app can warn about characters they can't.
// Run after changing the fonts in public/fonts:  node scripts/font-coverage.mjs
import { writeFileSync } from "node:fs";
import path from "node:path";
import { openSync } from "fontkit";

// Form values are drawn in regular and bold; italic is only used for fixed hint text.
const FONTS = ["NotoSerif-Regular.ttf", "NotoSerif-Bold.ttf"];

export function coverageRanges(fontDir) {
  const sets = FONTS.map((file) => new Set(openSync(path.join(fontDir, file)).characterSet));
  const shared = [...sets[0]].filter((cp) => sets.every((s) => s.has(cp))).sort((a, b) => a - b);
  const ranges = [];
  for (const cp of shared) {
    const last = ranges.at(-1);
    if (last && cp === last[1] + 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  return ranges;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
  const ranges = coverageRanges(path.join(root, "public", "fonts"));
  const body = ranges.map(([a, b]) => `[0x${a.toString(16)}, 0x${b.toString(16)}]`).join(",\n  ");
  writeFileSync(
    path.join(root, "src", "lib", "pdf-font-coverage.ts"),
    `// Generated by scripts/font-coverage.mjs from ${FONTS.join(" and ")}. Do not edit.\n` +
      `// Inclusive [first, last] Unicode code point ranges that the PDF fonts can draw.\n` +
      `export const PDF_FONT_COVERAGE: readonly (readonly [number, number])[] = [\n  ${body},\n];\n`,
  );
  console.log(`Wrote ${ranges.length} ranges.`);
}
